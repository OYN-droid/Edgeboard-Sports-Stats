function athlete(id, name, sportId, leagueId, teamId, aliases = [], options = {}) {
  return Object.freeze({
    id,
    name,
    entityType: options.entityType || "player",
    sportId,
    leagueId,
    teamId,
    aliases: Object.freeze(aliases),
    providerIds: Object.freeze(options.providerIds || { edgeboardMock: id }),
    active: options.active !== false,
    position: options.position || "",
    profile: MOCK_ATHLETE_PROFILE_METADATA[id] || Object.freeze({
      sample: true,
      shortName: name,
      teamName: teamId,
      organization: teamId,
      role: options.position || "",
      status: options.active === false ? "Inactive" : "Active",
      availabilityStatus: options.active === false ? "Inactive" : "Available",
      seasonLabel: "Illustrative sample",
      nextEvent: null,
      matchup: null,
    }),
    media: sampleMedia(name, sportId, options.media || {}),
  });
}

function team(id, name, sportId, leagueId, aliases = []) {
  return Object.freeze({
    id,
    name,
    entityType: "team",
    sportId,
    leagueId,
    teamId: id,
    aliases: Object.freeze(aliases),
    providerIds: Object.freeze({ edgeboardMock: id }),
    active: true,
    position: "",
    media: sampleMedia(name, sportId),
  });
}

